# HYPERLIQUID INTEGRATION (read-only planning; trade execution needs API secret)
# ─────────────────────────────────────────────────────────────────────────────

def hyperliquid_signal_plan(
    signal: AstroSignal,
    balance: float,
    current_price: float,
) -> dict:
    """Generate a Hyperliquid trade plan from a validated signal.

    Returns a plan dict that can be reviewed before execution.
    Does NOT execute — human or rule engine must approve.
    """
    size_pct = signal.suggested_size_pct
    notional = balance * size_pct
    size = notional / current_price if current_price > 0 else 0.0

    return {
        "signal_id": signal.signal_id,
        "venue": "hyperliquid",
        "asset": signal.asset,
        "direction": signal.direction,
        "size": round(size, 6),
        "notional_usdc": round(notional, 2),
        "leverage": min(3.0, signal.strength * 5.0),  # conservative
        "stop_loss_pct": signal.stop_loss_pct,
        "take_profit_pct": signal.take_profit_pct,
        "evidence_score": signal.evidence_score,
        "risk_ok": (
            size_pct <= 0.05
            and signal.evidence_score >= 71
        ),
    }


