class AstronacciAgent:
    """Main Astronacci agent: orchestrates ephemeris, features, validation, signals.

    This is the TOP-LEVEL orchestrator for the entire Astronacci system within
    Anantara Sakti. It does NOT make autonomous trading decisions — it generates
    validated signals that pass through the Epistemic Governor before any
    execution consideration.

    Usage:
        agent = AstronacciAgent(config)
        await agent.compute_cycle()  # run from daemon scheduler
    """

    def __init__(self, config: AstronacciConfig | None = None):
        self.cfg = config or AstronacciConfig()
        self.ephemeris = EphemerisEngine(ephemeris_dir=self.cfg.ephemeris_dir)
        self.feature_engine = AstronacciFeatureEngine()
        self.registry = EvidenceRegistry(registry_path=self.cfg.evidence_path)
        self.governor = EpistemicGovernor(self.registry)
        self.defense = StatisticalDefenseSystem()
        self.state = AstroState()
        self._audit_fh = None

    # ── Core compute cycle ──

    def compute_cycle(self) -> dict:
        """Run one compute cycle: ephemeris → features → events → signals.

        Called every N hours by the daemon scheduler.

        Returns summary dict for Telegram/audit.
        """
        now = datetime.now(timezone.utc)

        # Step 1: Compute ephemeris snapshot
        try:
            snap = self.ephemeris.compute(now)
        except Exception as e:
            log.error(f"Ephemeris compute failed: {e}")
            return {"error": str(e), "status": "ephemeris_failed"}

        # Step 2: Extract astro features
        features = compute_astro_features(snap)
        self.state.ephemeris_cache[now.isoformat()] = features

        # Step 3: Gate features through Epistemic Governor
        gate_result = self.governor.gate(features)

        # Step 4: Check for significant astro events
        events = self._detect_significant_events(snap)

        # Step 5: Generate signals from allowed features
        signals = []
        if gate_result["allowed"]:
            signal = self._generate_signal(
                snap, gate_result["allowed_features"], events,
            )
            if signal and signal.evidence_score >= self.cfg.min_evidence_for_trade:
                signals.append(signal)
                self._audit_signal(signal, gate_result)

        # Step 5b: Generate signals from PRODUCTION-status regime-conditional
        # edges (the honest-promotion path). The astro-only _generate_signal
        # above rarely fires; the real edges live in the registry as
        # "{signal}_{asset}_1d__{regime}_{value}" entries that survived the
        # 7-gate defense. This consults the live regime + RSI to emit signals
        # ONLY when the current market state matches a production edge.
        prod_signals = self._generate_production_signals()
        signals.extend(prod_signals)
        for s in prod_signals:
            self._audit_signal(s, gate_result)

        # Update state
        self.state.last_computed = now.isoformat()
        if signals:
            self.state.last_signal = signals[0]

        summary = {
            "timestamp": now.isoformat(),
            "status": "ok",
            "lunar_phase": round(snap.lunar.phase_angle, 1),
            "lunar_illumination": round(snap.lunar.illumination, 3),
            "retrograde_planets": [
                b.name for b in snap.bodies.values() if b.is_retrograde
            ],
            "significant_aspects": len([a for a in snap.aspects if a.proximity > 0.8]),
            "cluster_density": snap.cluster.density_score,
            "features_gated": gate_result["n_allowed"],
            "features_blocked": gate_result["n_blocked"],
            "signals_generated": len(signals),
            "signals": [asdict(s) for s in signals],
        }

        return summary

    def _detect_significant_events(
        self, snap: EphemerisSnapshot,
    ) -> list[dict]:
        """Detect significant astro events from snapshot."""
        events = []

        # Lunar events
        pa = snap.lunar.phase_angle
        if pa < 1.0 or pa > 359.0:
            events.append({"type": "new_moon", "proximity": 1.0})
        if 179.0 < pa < 181.0:
            events.append({"type": "full_moon", "proximity": 1.0})
        if pa < 5.0:
            events.append({"type": "near_new_moon", "proximity": 1.0 - pa / 5.0})
        if abs(pa - 180.0) < 5.0:
            events.append({"type": "near_full_moon", "proximity": 1.0 - abs(pa - 180.0) / 5.0})

        # Significant aspects (proximity > 0.9)
        for a in snap.aspects:
            if a.proximity > 0.9:
                events.append({
                    "type": f"aspect_{a.aspect_name}",
                    "bodies": f"{a.body_a}-{a.body_b}",
                    "proximity": a.proximity,
                })

        # Retrograde events
        retros = [b.name for b in snap.bodies.values() if b.is_retrograde]
        if "Mercury" in retros:
            events.append({"type": "mercury_retrograde", "proximity": 1.0})

        # Planetary cluster
        if snap.cluster.density_score > 0.6:
            events.append({
                "type": "planetary_cluster",
                "density": snap.cluster.density_score,
                "bodies": snap.cluster.participating,
            })

        return events

    def _generate_signal(
        self,
        snap: EphemerisSnapshot,
        allowed_features: dict[str, float],
        events: list[dict],
    ) -> AstroSignal | None:
        """Generate a trading signal from validated features and events.

        Currently uses a rule-based fusion model. Future: ML ensemble.
        """
        if not events:
            return None

        # Compute signal strength from event proximity and feature agreement
        event_score = sum(e.get("proximity", 0.0) for e in events) / max(len(events), 1)

        # Feature agreement: do lunar and aspect features point same direction?
        lunar_signal = 0.0
        # Full moon = potential reversal (bearish bias during bull, bullish during bear)
        if abs(snap.lunar.phase_angle - 180.0) < 10.0:
            lunar_signal = -0.3  # slight bearish bias near full moon
        elif snap.lunar.phase_angle < 10.0:
            lunar_signal = 0.3   # slight bullish bias near new moon

        # Aspect signal
        aspect_signal = 0.0
        opposition_max = allowed_features.get("aspect_opposition_max", 0.0)
        conjunction_max = allowed_features.get("aspect_conjunction_max", 0.0)
        if opposition_max > 0.8:
            aspect_signal -= 0.2  # opposition = tension = potential reversal
        if conjunction_max > 0.8:
            aspect_signal += 0.1  # conjunction = alignment

        # Combined signal
        raw_signal = lunar_signal + aspect_signal
        strength = abs(raw_signal) * event_score

        if strength < 0.15:
            return None  # too weak

        direction = "LONG" if raw_signal > 0 else "SHORT"

        # Evidence score + genuine defense_result from the registry.
        # We pick the triggering feature with the highest evidence score and
        # carry its stored defense_result (if any) onto the signal. This
        # closes the audit trail end-to-end: the paper-trade engine then
        # records the REAL gates_passed (TIER 2.5 fix) instead of a default 0.
        evidence = 0
        defense_result: dict | None = None
        for feat in ["lunar_illumination", "aspect_conjunction_max",
                      "aspect_opposition_max"]:
            entry = self.registry.get(feat)
            if entry and entry.evidence_score > evidence:
                evidence = entry.evidence_score
                dr = entry.test_results.get("defense_result")
                if isinstance(dr, dict):
                    defense_result = dr

        # Risk sizing (fractional Kelly style, conservative)
        size_pct = min(strength * 0.02, self.cfg.max_position_pct)

        signal_id = f"ASTRO-{datetime.now(timezone.utc).strftime('%Y%m%d-%H%M%S')}"

        return AstroSignal(
            signal_id=signal_id,
            timestamp=datetime.now(timezone.utc).isoformat(),
            asset="BTC",  # default; can be expanded
            direction=direction,
            strength=round(strength, 4),
            trigger_features={
                "lunar_phase": snap.lunar.phase_angle,
                "opposition_max": opposition_max,
                "conjunction_max": conjunction_max,
            },
            primary_event=events[0]["type"] if events else "",
            evidence_score=evidence,
            evidence_status=self.registry._score_to_status(evidence),
            suggested_size_pct=round(size_pct, 4),
            stop_loss_pct=round(0.03, 4),  # 3% stop
            take_profit_pct=round(0.06, 4),  # 6% TP (2:1 R:R)
            regime_tag="unknown",
            defense_result=defense_result,
        )

    # ── Audit ──

    def _generate_production_signals(self) -> list[AstroSignal]:
        """Emit signals from PRODUCTION registry edges that match the live regime.

        Round 9 — fundamental fix for the agent/improvement-loop decoupling.
        The improvement loop registers regime-conditional edges like
        `rsi_overbought_BTC_1d__trend_bull` when they survive the 7-gate
        defense, but the old _generate_signal only looked at generic lunar/
        aspect features and never consulted these edges. Result: 15 production
        signals existed but compute_cycle emitted 0 signals → paper trading
        never accumulated a track record.

        This reads the latest daily bar per asset, classifies the current
        regime (trend/volatility/risk), computes RSI, and emits a signal ONLY
        when (signal_type, asset, regime) matches a production registry entry
        AND the signal's directional trigger fires (RSI oversold→LONG,
        overbought→SHORT). Every emitted signal carries the registry's real
        defense_result so the paper trade records genuine gates_passed.
        """
        out: list[AstroSignal] = []
        try:
            from astronacci_pipeline import AstroDataPipeline
            from astronacci_improve import DeepAnalysisEngine, RegimeDetector
            pipe = AstroDataPipeline()
            det = RegimeDetector()
        except Exception as e:
            log.warning(f"production-signal deps unavailable: {e}")
            return out

        production = {
            name: entry for name, entry in self.registry._entries.items()
            if entry.status == "production"
        }
        if not production:
            return out

        # DIRECTIONAL EDGE FILTER (Round 10 — data-driven, verified on 5y data):
        # rsi_overbought→SHORT edges are net LOSING (PF 0.30) over 5 years
        # across all assets — the strong bull bias of crypto 2021-2026 wrecks
        # fade-the-rally shorts. rsi_oversold→LONG edges are strongly
        # profitable (PF ~4.0, OOS WR 67-86%). We therefore DO NOT emit
        # overbought-SHORT signals. The edges remain in the registry (not
        # deleted) so they can be re-evaluated if a sustained bear regime
        # emerges — this is a trade-execution filter, not a memory wipe.
        LONG_ONLY = True

        for asset in ("BTC", "ETH", "SOL", "HYPE", "BNB", "XRP", "DOGE", "BCH",
                      "ONDO", "LINK", "AAVE", "SUI", "UNI", "TRX", "ENA",
                      "ASTER", "PUMP", "LIT", "ARB", "LTC"):
            try:
                ds = pipe.load_dataset(asset, "1d")
                if not ds or ds.n_bars < 60:
                    continue
                prices = ds.price_series()
                regimes = det.detect(prices)
                idx = len(prices) - 1
                cur_trend = regimes.trend[idx] if idx < len(regimes.trend) else "unknown"
                cur_vol = regimes.volatility[idx] if idx < len(regimes.volatility) else "unknown"
                cur_risk = regimes.risk[idx] if idx < len(regimes.risk) else "unknown"
                rsi_series = DeepAnalysisEngine._rsi_series(prices)
                cur_rsi = rsi_series[idx] if idx < len(rsi_series) else 50.0
                last_bar = ds.bars[idx]
            except Exception as e:
                log.debug(f"production-signal {asset} skipped: {e}")
                continue

            # RCA FIX (audit 2026-09-04): this loop previously covered ONLY
            # rsi_oversold/rsi_overbought triggers. But the registry's
            # `production`-status edges are dominated by mercury_retrograde/
            # full_moon signal types (4 of 5 entries live 2026-09-04) — those
            # were NEVER checked here, so a signal that survived the 7-gate
            # defense could still never fire. Combined with LONG_ONLY (which
            # drops the 5th, an overbought/SHORT entry), the reachable set
            # was mathematically empty: 0 production signals ever emitted
            # (paper_portfolio.json never created despite weeks of 6h runs).
            # Astro triggers use the SAME detectors as training
            # (astronacci_improve._find_retrograde / _find_lunar_events) so
            # the live check matches what was actually validated, and the
            # SAME direction (LONG — training's `cars` is a raw forward
            # return, not a fade) so promotion and execution stay consistent.
            mercury_retro = last_bar.astro_features.get("Mercury_retrograde", 0) > 0.5
            lunar_sin = last_bar.astro_features.get("lunar_phase_sin", 0)
            lunar_cos = last_bar.astro_features.get("lunar_phase_cos", 0)
            lunar_angle = math.degrees(math.atan2(lunar_sin, lunar_cos)) % 360
            full_moon = min(abs(lunar_angle - 180.0), 360 - abs(lunar_angle - 180.0)) <= 7.0
            new_moon = min(abs(lunar_angle - 0.0), 360 - abs(lunar_angle - 0.0)) <= 7.0

            # For each regime dimension, check if a production edge matches
            # and its directional trigger fires now.
            for sig_type, trigger_dir, trigger_cond in (
                ("rsi_oversold", "LONG", cur_rsi < 30.0),
                ("rsi_overbought", "SHORT", cur_rsi > 70.0),
                ("mercury_retrograde", "LONG", mercury_retro),
                ("full_moon", "LONG", full_moon),
                ("new_moon", "LONG", new_moon),
            ):
                if not trigger_cond:
                    continue
                # LONG_ONLY filter: skip the data-confirmed-losing SHORT path.
                if LONG_ONLY and trigger_dir == "SHORT":
                    continue
                for reg_type, reg_val in (
                    ("trend", cur_trend), ("volatility", cur_vol), ("risk", cur_risk),
                ):
                    if reg_val == "unknown":
                        continue
                    name = f"{sig_type}_{asset}_1d__{reg_type}_{reg_val}"
                    entry = production.get(name)
                    if not entry:
                        continue
                    dr = entry.test_results.get("defense_result", {})
                    gates = int(dr.get("gates_passed", 0)) if isinstance(dr, dict) else 0
                    signal_id = f"ASTRO-PROD-{datetime.now(timezone.utc).strftime('%Y%m%d-%H%M%S')}-{asset}"
                    out.append(AstroSignal(
                        signal_id=signal_id,
                        timestamp=datetime.now(timezone.utc).isoformat(),
                        asset=asset,
                        direction=trigger_dir,
                        strength=0.5,
                        trigger_features={"rsi": cur_rsi, reg_type: reg_val},
                        primary_event=name,
                        evidence_score=entry.evidence_score,
                        evidence_status="production",
                        suggested_size_pct=min(self.cfg.max_position_pct, 0.03),
                        stop_loss_pct=0.03,
                        take_profit_pct=0.06,
                        regime_tag=f"{reg_type}_{reg_val}",
                        defense_result=dr if isinstance(dr, dict) else None,
                    ))
                    break  # one signal per asset per trigger
        return out

    def _audit_signal(self, signal: AstroSignal, gate_result: dict):
        """Write signal to audit log."""
        record = {
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "signal_id": signal.signal_id,
            "direction": signal.direction,
            "strength": signal.strength,
            "evidence_score": signal.evidence_score,
            "trigger_features": signal.trigger_features,
            "primary_event": signal.primary_event,
            "gate_result": {
                "n_allowed": gate_result["n_allowed"],
                "n_blocked": gate_result["n_blocked"],
            },
        }
        try:
            audit_path = Path(self.cfg.audit_log_path)
            audit_path.parent.mkdir(parents=True, exist_ok=True)
            with open(audit_path, "a") as f:
                f.write(json.dumps(record) + "\n")
        except Exception as e:
            log.error(f"Audit write failed: {e}")

